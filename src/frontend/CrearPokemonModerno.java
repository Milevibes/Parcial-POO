    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        String nombre = jTextField1.getText().trim();
        String numero = jTextField2.getText().trim();
        String tipo = jTextField4.getText().trim();
        String nivel = jTextField3.getText().trim();

        if (nombre.isEmpty() || numero.isEmpty() || tipo.isEmpty() || nivel.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa todos los campos del Pokemon.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (nombre.contains(",") || tipo.contains(",")) {
            JOptionPane.showMessageDialog(this, "El nombre y el tipo no pueden contener comas.",
                    "Dato invalido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!numero.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "El numero debe ser un valor numerico.",
                    "Dato invalido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!nivel.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "El nivel debe ser un valor numerico.",
                    "Dato invalido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int nivelNumero = Integer.parseInt(nivel);
        if (nivelNumero < 1 || nivelNumero > 100) {
            JOptionPane.showMessageDialog(this, "El nivel debe estar entre 1 y 100.",
                    "Dato invalido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Pokemon pokemon = new Pokemon(nombre, numero, tipo, nivel);

        if (OperationsPokemon.savePokemon(pokemon)) {
            JOptionPane.showMessageDialog(this, "Pokemon guardado correctamente.",
                    "Pokemon", JOptionPane.INFORMATION_MESSAGE);
            abrirListaPokemones();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo guardar el Pokemon.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

